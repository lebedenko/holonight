"""Generate the production installer profile from canonical adoption declarations."""
import argparse
import json
from pathlib import Path
import sys
from external import package_names, probe_source

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    configs = [json.loads(p.read_text()) for p in sorted((ROOT / 'tooling/modules').glob('*.json'))]
    names = package_names(configs, 'arch')
    shell = '# Generated by tooling/generate-install-profile.py; do not edit.\n'
    shell += 'readonly HOLONIGHT_INSTALL_PACKAGES=(\n' + ''.join('  ' + p + '\n' for p in names) + ')\n'
    result = {ROOT / 'scripts/install-profile.sh': shell,
              ROOT / 'tooling/install-profile.cmake': probe_source(configs, ('build', 'tool', 'runtime'))}
    extras = {'go-task', 'clang', 'reuse', 'gcovr', 'qt6-tools', 'qt5-base', 'mesa', 'binutils', 'ripgrep',
              'desktop-file-utils', 'appstream', 'xorg-xauth', 'noto-fonts'}
    full = sorted((set(package_names(configs, 'arch', ('build', 'tool', 'test', 'runtime'))) - {'qmarkdown'}) | extras)
    daemon = next(c for c in configs if c['module'] == 'holonightd')
    minimal = sorted(set(package_names([daemon], 'arch', ('build', 'tool', 'test'))) |
                     {'clang', 'gcovr', 'go-task', 'reuse'})
    result[ROOT / 'packaging/ci/arch-full.packages'] = '\n'.join(full) + '\n'
    result[ROOT / 'packaging/ci/arch-daemon.packages'] = '\n'.join(minimal) + '\n'
    for config in configs:
        snippet = '# Generated from module.json; external libraries use normal package discovery.\n'
        snippet += 'include("${CMAKE_CURRENT_LIST_DIR}/providers.cmake")\n'
        snippet += ''.join(f'holonight_require_provider({item["package"]})\n' for item in config.get('dependencies', []))
        result[ROOT / 'tooling/modules' / (config['module'] + '.cmake')] = snippet
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text() != text:
            drift.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(text)
    if args.check and drift:
        print('Stale installation profile: ' + ', '.join(drift), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
